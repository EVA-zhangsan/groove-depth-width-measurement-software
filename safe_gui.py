def load_point_cloud(path: Path) -> np.ndarray:
    suffix = path.suffix.lower()
    if suffix == ".csv":
        frame = pd.read_csv(path)
        if {"x", "y", "z"}.issubset(frame.columns):
            return frame[["x", "y", "z"]].to_numpy(float)
        if frame.shape[1] >= 3:
            return frame.iloc[:, :3].to_numpy(float)
        raise ValueError("CSV 至少需要三列或 x、y、z 三列")
    if suffix in {".xyz", ".txt"}:
        data = np.loadtxt(path, dtype=float)
        if data.ndim != 2 or data.shape[1] < 3:
            raise ValueError("XYZ/TXT 点云至少需要三列")
        return data[:, :3]
    raise ValueError("安全版为避免 VTK 依赖，仅支持 CSV / XYZ / TXT 点云。")


def array_to_pixmap(image: np.ndarray, target: QLabel) -> QPixmap:
    if image.ndim == 2:
        rgb = cv2.cvtColor(image, cv2.COLOR_GRAY2RGB)
    else:
        rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    rgb = np.ascontiguousarray(rgb)
    h, w, c = rgb.shape
    qimg = QImage(rgb.data, w, h, w * c, QImage.Format_RGB888).copy()
    return QPixmap.fromImage(qimg).scaled(target.size(), Qt.KeepAspectRatio, Qt.SmoothTransformation)


def render_cpu_projection(points: np.ndarray, width: int = 1080, height: int = 720) -> np.ndarray:
    """Render a stable pseudo-3D perspective image using CPU only (no OpenGL)."""
    pts = np.asarray(points, dtype=float)
    if pts.ndim != 2 or pts.shape[1] < 3 or pts.shape[0] < 3:
        raise ValueError("点云数据无效")

    # Deterministic downsample for display only; analysis always uses the full cloud.
    max_display = 95000
    if pts.shape[0] > max_display:
        stride = int(np.ceil(pts.shape[0] / max_display))
        draw_pts = pts[::stride].copy()
    else:
        draw_pts = pts.copy()

    # Center and normalize visual aspect.  Y is physically much longer than the transverse
    # section, so compress it only for visualization, similar to an interactive 3D camera.
    xyz = draw_pts[:, :3].copy()
    center = np.nanmedian(xyz, axis=0)
    xyz -= center
    ranges = np.ptp(xyz, axis=0)
    xr = max(ranges[0], 1e-9)
    yr = max(ranges[1], 1e-9)
    zr = max(ranges[2], 1e-9)
    xyz[:, 1] *= (xr / yr) * 2.55
    xyz[:, 2] *= (xr / zr) * 0.82

    # Fixed competition-friendly isometric-like view.
    yaw = np.deg2rad(-34.0)
    pitch = np.deg2rad(58.0)
    rz = np.array([[np.cos(yaw), -np.sin(yaw), 0.0],
                   [np.sin(yaw),  np.cos(yaw), 0.0],
                   [0.0, 0.0, 1.0]])
    rx = np.array([[1.0, 0.0, 0.0],
                   [0.0, np.cos(pitch), -np.sin(pitch)],
                   [0.0, np.sin(pitch),  np.cos(pitch)]])
    rot = xyz @ (rx @ rz).T
    u = rot[:, 0]
    v = -rot[:, 2]

    canvas = np.zeros((height, width, 3), dtype=np.uint8)
    canvas[:] = (24, 31, 38)

    # Fit the projected cloud into the canvas.
    margin_x, margin_y = 70, 65
    ur = max(float(np.ptp(u)), 1e-9)
    vr = max(float(np.ptp(v)), 1e-9)
    scale = min((width - 2 * margin_x) / ur, (height - 2 * margin_y) / vr)
    px = ((u - u.min()) * scale + margin_x).astype(np.int32)
    py = ((v - v.min()) * scale + margin_y).astype(np.int32)

    # Height colors, generated by OpenCV on CPU.
    z = draw_pts[:, 2]
    zmin, zmax = float(np.nanmin(z)), float(np.nanmax(z))
    zn = ((z - zmin) / max(zmax - zmin, 1e-9) * 255.0).clip(0, 255).astype(np.uint8)
    colors = cv2.applyColorMap(zn.reshape(-1, 1), cv2.COLORMAP_TURBO).reshape(-1, 3)

    # Draw points from back to front for a more readable surface.
    order = np.argsort(rot[:, 1])
    for idx in order:
        x, y = int(px[idx]), int(py[idx])
        if 0 <= x < width and 0 <= y < height:
            c = tuple(int(vv) for vv in colors[idx])
            cv2.circle(canvas, (x, y), 1, c, -1, lineType=cv2.LINE_AA)

    # Draw representative cross-section polylines as an independent, very visible layer.
    full = np.asarray(points[:, :3], dtype=float)
    rounded_y = np.round(full[:, 1], 6)
    unique_y = np.unique(rounded_y)
    stride_y = max(1, len(unique_y) // 34)
    for y_value in unique_y[::stride_y]:
        sec = full[rounded_y == y_value]
        if sec.shape[0] < 3:
            continue
        sec = sec[np.argsort(sec[:, 0])]
        sec_vis = sec.copy()
        sec_vis[:, :3] -= center
        sec_vis[:, 1] *= (xr / yr) * 2.55
        sec_vis[:, 2] *= (xr / zr) * 0.82
        srot = sec_vis @ (rx @ rz).T
        su = ((srot[:, 0] - u.min()) * scale + margin_x).astype(np.int32)
        sv = ((-srot[:, 2] - v.min()) * scale + margin_y).astype(np.int32)
        poly = np.column_stack([su, sv]).reshape(-1, 1, 2)
        cv2.polylines(canvas, [poly], False, (55, 105, 255), 1, cv2.LINE_AA)

    # Labels deliberately say "CPU兼容投影" so it is clear why this view is stable.
    cv2.putText(canvas, "CPU Safe 3D Projection", (28, 34), cv2.FONT_HERSHEY_SIMPLEX, 0.78, (230, 238, 245), 2, cv2.LINE_AA)
    cv2.putText(canvas, f"Points: {points.shape[0]}   Z range: {zmin:.3f} ~ {zmax:.3f} mm", (28, height - 24), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (170, 190, 205), 1, cv2.LINE_AA)
    return canvas


