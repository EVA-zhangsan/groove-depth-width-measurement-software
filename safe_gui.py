    def render_points(self):
        if self.points is None: return
        image = render_cpu_projection(self.points, 1080, 720)
        self.viewer_label.setPixmap(array_to_pixmap(image, self.viewer_label))
        self.viewer_label.setToolTip("CPU 兼容投影：不使用 VTK/OpenGL；数值分析仍基于完整三维点云。")

    def update_images(self):
        if not self.reconstruction: return
        paths = {"原始图像":self.reconstruction.get("preview_original"),"中心提取":self.reconstruction.get("preview_overlay"),"二值掩膜":self.reconstruction.get("preview_mask")}
        for name, path in paths.items():
            if path and Path(path).exists():
                image = imread_unicode(path, cv2.IMREAD_UNCHANGED)
                if image is not None: self.image_labels[name].setPixmap(array_to_pixmap(image, self.image_labels[name]))

    def update_results(self):
        if not self.result or not self.reconstruction or not self.task: return
        depth_ok = abs(self.result.depth_mean-self.task.target_depth_mm) <= self.task.tolerance_mm
        width_ok = abs(self.result.width_mean-self.task.target_width_mm) <= self.task.tolerance_mm
        values = {
            "槽深均值":f"{self.result.depth_mean:.4f} mm", "槽宽均值":f"{self.result.width_mean:.4f} mm",
            "槽深均值判定":"合格" if depth_ok else "超差", "槽宽均值判定":"合格" if width_ok else "超差",
            "槽深最小值及位置":f"{self.result.depth_min:.4f} mm @ Y={self.result.depth_min_y:.3f}",
            "槽深最大值及位置":f"{self.result.depth_max:.4f} mm @ Y={self.result.depth_max_y:.3f}",
            "槽宽最小值及位置":f"{self.result.width_min:.4f} mm @ Y={self.result.width_min_y:.3f}",
            "槽宽最大值及位置":f"{self.result.width_max:.4f} mm @ Y={self.result.width_max_y:.3f}",
            "有效截面":str(len(self.result.sections)), "点云点数":str(self.reconstruction.get("point_count",0)),
            "读取/重建耗时":f"{self.reconstruction.get('read_seconds',0):.3f} s", "分析耗时":f"{self.result.analysis_seconds:.3f} s",
        }
        for k,v in values.items(): self.result_labels[k].setText(v)
        for k in ["槽深均值判定","槽宽均值判定"]:
            self.result_labels[k].setStyleSheet("color:#65e58a;font-weight:700;" if self.result_labels[k].text()=="合格" else "color:#ff7373;font-weight:700;")

